-- 1. ตารางรายชื่อนักเรียน (std)
CREATE TABLE IF NOT EXISTS public.std (
    student_id TEXT PRIMARY KEY,
    grade TEXT NOT NULL,
    room TEXT NOT NULL,
    no INTEGER DEFAULT 0,
    prefix TEXT DEFAULT '',
    first_name TEXT DEFAULT '',
    last_name TEXT DEFAULT '',
    full_name TEXT NOT NULL,
    gender TEXT DEFAULT '',
    status TEXT DEFAULT 'เข้า',
    out_reason TEXT DEFAULT '',
    out_date TEXT DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- เพิ่มคอลัมน์รองรับสถานะ เข้า/ออก สำหรับตาราง std ที่มีอยู่เดิม
ALTER TABLE public.std ADD COLUMN IF NOT EXISTS status TEXT DEFAULT 'เข้า';
ALTER TABLE public.std ADD COLUMN IF NOT EXISTS out_reason TEXT DEFAULT '';
ALTER TABLE public.std ADD COLUMN IF NOT EXISTS out_date TEXT DEFAULT '';

-- 2. ตารางผู้ใช้งาน / ครู (usr)
CREATE TABLE IF NOT EXISTS public.usr (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT UNIQUE NOT NULL,
    pin TEXT DEFAULT '1234',
    role TEXT DEFAULT 'TEACHER',
    code TEXT DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. ตารางวันหยุด (hol)
CREATE TABLE IF NOT EXISTS public.hol (
    date TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. ตารางบันทึกเวลาเรียน (att)
CREATE TABLE IF NOT EXISTS public.att (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date TEXT NOT NULL,
    grade TEXT NOT NULL,
    room TEXT NOT NULL,
    student_id TEXT NOT NULL,
    status TEXT NOT NULL,
    CONSTRAINT att_date_student_unique UNIQUE (date, student_id)
);

CREATE INDEX IF NOT EXISTS idx_att_date ON public.att(date);
CREATE INDEX IF NOT EXISTS idx_att_student ON public.att(student_id);
CREATE INDEX IF NOT EXISTS idx_att_grade_room ON public.att(grade, room);

-- 5. ตารางติดตามกลุ่มเสี่ยง ป.ค.8 & ป.ค.9 (pk8_pk9)
CREATE TABLE IF NOT EXISTS public.pk8_pk9 (
    student_id TEXT NOT NULL,
    doc_type TEXT NOT NULL,
    notice_count INTEGER DEFAULT 1,
    hr_name TEXT DEFAULT '',
    sa_name TEXT DEFAULT '',
    parent_name TEXT DEFAULT '',
    doc_date TEXT DEFAULT '',
    reason TEXT DEFAULT '',
    hr_sign TEXT DEFAULT '',
    sa_sign TEXT DEFAULT '',
    parent_sign TEXT DEFAULT '',
    PRIMARY KEY (student_id, doc_type, notice_count)
);

CREATE INDEX IF NOT EXISTS idx_pk8_pk9_student ON public.pk8_pk9(student_id);

-- 6. ตารางบันทึกการผ่อนผันนักเรียน (exm)
CREATE TABLE IF NOT EXISTS public.exm (
    student_id TEXT PRIMARY KEY,
    type TEXT DEFAULT 'ทั้งหมด',
    reason TEXT DEFAULT ''
);

-- 7. ตารางบันทึกการขออนุญาตออกนอกบริเวณ (pk11)
CREATE TABLE IF NOT EXISTS public.pk11 (
    id TEXT PRIMARY KEY,
    target_date TEXT NOT NULL,
    student_id TEXT NOT NULL,
    exit_time TEXT DEFAULT '',
    return_time TEXT DEFAULT '',
    reason TEXT DEFAULT '',
    location TEXT DEFAULT '',
    parent_name TEXT DEFAULT '',
    relation TEXT DEFAULT '',
    student_phone TEXT DEFAULT '',
    parent_phone TEXT DEFAULT '',
    hr_name TEXT DEFAULT '',
    sa_name TEXT DEFAULT '',
    hr_status BOOLEAN DEFAULT TRUE,
    status BOOLEAN DEFAULT TRUE,
    student_signature TEXT DEFAULT '',
    parent_signature TEXT DEFAULT '',
    hr_signature TEXT DEFAULT '',
    sa_signature TEXT DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_pk11_target_date ON public.pk11(target_date);
CREATE INDEX IF NOT EXISTS idx_pk11_student ON public.pk11(student_id);

-- 8. ตารางบันทึกความประพฤติ (mis)
CREATE TABLE IF NOT EXISTS public.mis (
    id TEXT PRIMARY KEY,
    date TEXT NOT NULL,
    student_id TEXT DEFAULT '-',
    description TEXT NOT NULL,
    recorder TEXT DEFAULT 'T001',
    resolved BOOLEAN DEFAULT FALSE,
    resolution TEXT DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_mis_date ON public.mis(date);
CREATE INDEX IF NOT EXISTS idx_mis_student ON public.mis(student_id);

-- 9. ตารางบันทึกผลการประเมินความสะอาด 5ส. (evaluations)
CREATE TABLE IF NOT EXISTS public.evaluations (
    eval_date DATE NOT NULL,
    room_name VARCHAR(20) NOT NULL,
    r_clean INT DEFAULT 5,
    sw_fan INT DEFAULT 0,
    sw_brd INT DEFAULT 0,
    sw_tsh INT DEFAULT 0,
    sw_chr INT DEFAULT 0,
    classroom_note TEXT DEFAULT '',
    is_classroom_saved BOOLEAN DEFAULT false,
    a_clean INT DEFAULT 5,
    sw_tls INT DEFAULT 0,
    service_note TEXT DEFAULT '',
    is_service_saved BOOLEAN DEFAULT false,
    PRIMARY KEY (eval_date, room_name)
);

CREATE INDEX IF NOT EXISTS idx_evaluations_date ON public.evaluations(eval_date);
CREATE INDEX IF NOT EXISTS idx_evaluations_room ON public.evaluations(room_name);

-- 10. ตารางบันทึกการตรวจระเบียบทรงผม (hair - เก็บเฉพาะคนที่ยังไม่ตัดผม)
CREATE TABLE IF NOT EXISTS public.hair (
    check_date DATE NOT NULL,
    student_id TEXT NOT NULL,
    note TEXT DEFAULT '',
    PRIMARY KEY (check_date, student_id)
);

CREATE INDEX IF NOT EXISTS idx_hair_date ON public.hair(check_date);
CREATE INDEX IF NOT EXISTS idx_hair_student ON public.hair(student_id);

-- 11. ตารางแบบประเมินความเครียดและอารมณ์ซึมเศร้า (stress_eval)
CREATE TABLE IF NOT EXISTS public.stress_eval (
    id TEXT PRIMARY KEY,
    eval_date DATE NOT NULL,
    student_id TEXT NOT NULL,
    stress_score INT NOT NULL,
    stress_level TEXT NOT NULL,
    depression_score INT NOT NULL,
    depression_level TEXT NOT NULL,
    answers JSONB NOT NULL,
    q14_risk BOOLEAN DEFAULT FALSE,
    recorder TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_stress_eval_date ON public.stress_eval(eval_date);
CREATE INDEX IF NOT EXISTS idx_stress_eval_student ON public.stress_eval(student_id);

-- 12. ตารางแบบประเมินจุดเด่นและจุดด้อย SDQ (sdq_eval)
CREATE TABLE IF NOT EXISTS public.sdq_eval (
    id TEXT PRIMARY KEY,
    eval_date DATE NOT NULL,
    student_id TEXT NOT NULL,
    total_score INT NOT NULL,
    prosocial_score INT NOT NULL,
    overall_status TEXT NOT NULL,
    overall_title TEXT NOT NULL,
    emotional_score INT NOT NULL,
    conduct_score INT NOT NULL,
    hyperactivity_score INT NOT NULL,
    peer_score INT NOT NULL,
    subscales JSONB NOT NULL,
    answers JSONB NOT NULL,
    recorder TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_sdq_eval_date ON public.sdq_eval(eval_date);
CREATE INDEX IF NOT EXISTS idx_sdq_eval_student ON public.sdq_eval(student_id);

-- 13. ตารางแบบประเมินความเสี่ยงต่อการทำร้ายตนเอง (suicide_eval)
CREATE TABLE IF NOT EXISTS public.suicide_eval (
    id TEXT PRIMARY KEY,
    eval_date DATE NOT NULL,
    student_id TEXT NOT NULL,
    total_score INT NOT NULL,
    risk_level TEXT NOT NULL,
    risk_title TEXT NOT NULL,
    answers JSONB NOT NULL,
    recorder TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_suicide_eval_date ON public.suicide_eval(eval_date);
CREATE INDEX IF NOT EXISTS idx_suicide_eval_student ON public.suicide_eval(student_id);

