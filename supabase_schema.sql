-- ส่วนที่ 3: ตารางอเนกประสงค์สำหรับฟอร์มใหม่ (app_data - JSONB)
-- -------------------------------------------------------------
-- 14. ตารางอเนกประสงค์ (ใช้กับหน้ารีวิวโรงอาหาร และฟอร์มใหม่ๆ โดยไม่ต้องแก้ตารางอีก)
CREATE TABLE IF NOT EXISTS public.app_data (
    id TEXT PRIMARY KEY DEFAULT gen_random_uuid(),
    module TEXT NOT NULL,         -- เช่น 'canteen', 'survey', 'club'
    student_id TEXT DEFAULT '',   -- รหัสนักเรียน (ถ้ามี)
    date TEXT DEFAULT '',         -- วันที่บันทึก (YYYY-MM-DD)
    data JSONB NOT NULL,         -- ข้อมูลรีวิวหรือฟอร์มแบบยืดหยุ่น (JSON)
    created_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_app_data_module ON public.app_data(module);
CREATE INDEX IF NOT EXISTS idx_app_data_date ON public.app_data(date);
CREATE INDEX IF NOT EXISTS idx_app_data_student ON public.app_data(student_id);

